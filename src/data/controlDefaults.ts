export function getControlTypeInfo(type: number): ControlTypeInfo | undefined {
  return CONTROL_TYPES.find(ct => ct.type === type);
}

export function getControlTypeLabel(type: number): string {
  return getControlTypeInfo(type)?.label ?? `Unknown (${type})`;
}

export function getControlTypesByCategory(): Record<string, ControlTypeInfo[]> {
  const map: Record<string, ControlTypeInfo[]> = {};
  for (const ct of CONTROL_TYPES) {
    if (!map[ct.category]) map[ct.category] = [];
    map[ct.category].push(ct);
  }
  return map;
}
